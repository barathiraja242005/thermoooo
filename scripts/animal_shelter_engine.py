def calculate_thi(temp_c: float, relative_humidity_pct: float) -> float:
    """
    Computes standard NRC Temperature-Humidity Index (THI) for livestock.
    Formula: THI = (1.8 * T_c + 32) - (0.55 - 0.0055 * RH) * (1.8 * T_c - 26)
    Or bioclimatic formula: THI = 0.8 * T_c + (RH/100) * (T_c - 14.4) + 46.4
    """
    return 0.8 * temp_c + (relative_humidity_pct / 100.0) * (temp_c - 14.4) + 46.4


